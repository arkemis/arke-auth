defmodule ArkeAuth.Boundary.OtpManager do
  @moduledoc """
  Reads and verifies the codes generated by `ArkeAuth.Core.Otp`.
  """
  alias ArkeAuth.Core.Otp
  alias ArkeAuth.Boundary.{AttemptLimiter, TokenStore}
  alias ArkeAuth.Utils.TokenCrypto
  alias Arke.Utils.ErrorGenerator, as: Error

  @doc """
  The current code of `member` for `action`, without the code itself (only
  its HMAC is stored), or `nil` when there is none.

  When OTP_BYPASS_CODE is set, it replaces the member's code for every action
  in every project, and is returned in `data.code`. It is a deployment-wide
  second factor bypass, meant for local development only.
  """
  def get_code(project, member, action \\ "signin")

  def get_code(project, member, action) when is_atom(action),
    do: get_code(project, member, to_string(action))

  def get_code(project, member, action) do
    case bypass_code() do
      nil ->
        case TokenStore.get(Otp.store_key(project, action, member.id)) do
          nil -> nil
          entry -> Otp.to_otp(project, action, to_string(member.id), entry)
        end

      code ->
        %{
          id: Otp.parse_otp_id(action, member.id),
          metadata: %{project: project, subject: to_string(member.id)},
          bypass: true,
          data: %{
            code: code,
            action: action,
            expiry_datetime: NaiveDateTime.utc_now() |> NaiveDateTime.add(300, :second)
          }
        }
    end
  end

  defp bypass_code() do
    case System.get_env("OTP_BYPASS_CODE") do
      nil -> nil
      "" -> nil
      code -> code
    end
  end

  @default_max_attempts 5

  @doc """
  Checks `submitted` against the stored `action` code of `member` (a member
  map, or the raw id the code was generated for, e.g. a username at signup).

  A code verifies at most once, also when two requests race: it is consumed
  with `TokenStore.take/1`. It is deleted on expiry and once
  `config :arke_auth, ArkeAuth.Otp, max_attempts: n` (default
  #{@default_max_attempts}) wrong guesses have been made against it. The
  comparison runs in constant time on HMACs.

  ## Return
      {:ok, otp}
      {:error, [%{context: "auth", message: "invalid otp"}]}
      {:error, [%{context: "auth", message: "otp expired"}]}
      {:error, [%{context: "auth", message: "too many attempts"}]}
  """
  @spec verify_code(atom(), map() | String.t() | atom(), String.t() | atom(), term()) ::
          {:ok, map()} | Arke.Utils.ErrorGenerator.t()
  def verify_code(project, member, action, submitted)

  def verify_code(project, member, action, submitted) when is_atom(action),
    do: verify_code(project, member, to_string(action), submitted)

  def verify_code(project, member, action, submitted) when not is_map(member),
    do: verify_code(project, %{id: member}, action, submitted)

  def verify_code(project, member, action, submitted) do
    case get_code(project, member, action) do
      nil -> Error.create(:auth, "invalid otp")
      %{bypass: true} = otp -> check_bypass(otp, submitted)
      otp -> check_code(project, action, to_string(member.id), otp, submitted)
    end
  end

  defp check_code(project, action, subject, otp, submitted) do
    store_key = Otp.store_key(project, action, subject)
    attempt_key = Otp.attempt_key(project, action, subject)
    entry = TokenStore.get(store_key)

    cond do
      is_nil(entry) ->
        Error.create(:auth, "invalid otp")

      expired?(entry.expiry_datetime) ->
        TokenStore.delete(store_key)
        AttemptLimiter.reset(attempt_key)
        Error.create(:auth, "otp expired")

      AttemptLimiter.count(attempt_key) >= max_attempts() ->
        TokenStore.delete(store_key)
        Error.create(:auth, "too many attempts")

      right_code?(project, action, subject, entry, submitted) ->
        # Only the request that takes the entry succeeds.
        case TokenStore.take(store_key) do
          nil ->
            Error.create(:auth, "invalid otp")

          _entry ->
            AttemptLimiter.reset(attempt_key)
            {:ok, otp}
        end

      AttemptLimiter.hit(attempt_key, seconds_left(entry.expiry_datetime)) >= max_attempts() ->
        TokenStore.delete(store_key)
        Error.create(:auth, "too many attempts")

      true ->
        Error.create(:auth, "invalid otp")
    end
  end

  defp right_code?(project, action, subject, entry, submitted) do
    candidate = Otp.code_hmac(project, action, subject, normalize(submitted, entry.digits))
    TokenCrypto.secure_compare(candidate, entry.code_hmac)
  end

  # The bypass code never changes, so its window is per member and action and
  # is left to expire on its own once locked (not reset), throttling guesses.
  defp check_bypass(%{id: id, metadata: %{project: project}} = otp, submitted) do
    key = {:otp_bypass, project, to_string(id)}
    code = otp.data.code

    cond do
      AttemptLimiter.count(key) >= max_attempts() ->
        Error.create(:auth, "too many attempts")

      secure_compare(code, normalize(submitted, String.length(code))) ->
        AttemptLimiter.reset(key)
        {:ok, otp}

      AttemptLimiter.hit(key, 300) >= max_attempts() ->
        Error.create(:auth, "too many attempts")

      true ->
        Error.create(:auth, "invalid otp")
    end
  end

  defp expired?(nil), do: true

  defp expired?(expiry),
    do: NaiveDateTime.compare(expiry, NaiveDateTime.utc_now()) != :gt

  defp seconds_left(expiry),
    do: max(NaiveDateTime.diff(expiry, NaiveDateTime.utc_now(), :second), 1)

  defp max_attempts(), do: Otp.config(:max_attempts, @default_max_attempts)

  # JSON clients may send the code as a number, dropping its leading zeros.
  defp normalize(submitted, digits) when is_integer(submitted) and submitted >= 0,
    do: submitted |> Integer.to_string() |> String.pad_leading(digits, "0")

  defp normalize(submitted, _digits), do: to_string(submitted)

  # Hashing first gives equal-length inputs, so neither the content nor the
  # length of the code leaks through timing.
  defp secure_compare(left, right),
    do: TokenCrypto.secure_compare(:crypto.hash(:sha256, left), :crypto.hash(:sha256, right))

  @doc """
  Deletes the code behind an otp map returned by `ArkeAuth.Core.Otp` or by
  this module. The bypass code is never stored.
  """
  def delete_otp(%{bypass: true}), do: nil

  def delete_otp(%{data: %{action: action}, metadata: %{project: project, subject: subject}}),
    do: TokenStore.delete(Otp.store_key(project, action, subject))

  def delete_otp(_otp), do: nil
end
